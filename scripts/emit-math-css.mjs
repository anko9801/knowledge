#!/usr/bin/env node
/**
 * Typst が <head> に注入する MathML 用 stylesheet を 1 度だけ回収して
 * src/styles/typst-math.css に書き出す。
 *
 * Typst 0.15 はこの CSS を全ページの <head> に丸ごと重ねて出力する（約 1.6KB）。
 * body だけ抜き出す構成ではこれが落ちて数式が崩れ、かといってページ毎に
 * インライン化すると記事数ぶん重複する。共有 CSS として 1 回だけ配るのが答え。
 *
 * typst を上げたら再実行して差分を確認すること。prebuild で回すのが前提。
 */
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { mkdir, mkdtemp, rm, writeFile, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const run = promisify(execFile)

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(ROOT, 'src/styles/typst-math.css')
const TYPST = process.env.TYPST_BIN ?? 'typst'

/** MathML の主要な構文を一通り踏ませて、CSS 規則を漏れなく吐かせるための probe。 */
const PROBE = `#set text(lang: "ja")
$ x $
$ 1/2 + sqrt(2) + hat(x) + dot(y) $
$ cases(a &= 1, b &= 2) $
$ mat(1, 2; 3, 4) $
$ integral_0^oo f(x) dif x $
`

const extractStyles = (html) => {
  const head = html.match(/<head\b[^>]*>([\s\S]*?)<\/head>/)
  if (!head) {
    throw new Error('Typst の出力に <head> が見つかりません。出力形式が変わった可能性があります。')
  }

  const styles = [...head[1].matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)]
  if (styles.length === 0) {
    throw new Error(
      '<head> に <style> がありません。数式を含む文書のはずなので、' +
        'MathML export が有効になっているか確認してください。',
    )
  }

  return styles.map((m) => m[1].trim()).join('\n\n')
}

const main = async () => {
  const workdir = await mkdtemp(join(tmpdir(), 'typst-math-css-'))

  try {
    const probePath = join(workdir, 'probe.typ')
    await writeFile(probePath, PROBE, 'utf8')

    const { stdout } = await run(
      TYPST,
      ['compile', probePath, '--format', 'html', '--features', 'html', '--root', workdir, '-'],
      { maxBuffer: 16 * 1024 * 1024 },
    )

    const css = extractStyles(stdout)
    const banner = '/* generated by scripts/emit-math-css.mjs -- do not edit */\n'
    const next = `${banner}${css}\n`

    const previous = await readFile(OUTPUT, 'utf8').catch(() => null)
    if (previous === next) {
      process.stdout.write(`typst-math.css は最新です (${Buffer.byteLength(css)} bytes)\n`)
      return
    }

    await mkdir(dirname(OUTPUT), { recursive: true })
    await writeFile(OUTPUT, next, 'utf8')
    process.stdout.write(
      `${previous === null ? '生成' : '更新'}: src/styles/typst-math.css (${Buffer.byteLength(css)} bytes)\n`,
    )
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error)
    process.stderr.write(`MathML stylesheet の抽出に失敗しました:\n${detail}\n`)
    process.exitCode = 1
  } finally {
    await rm(workdir, { recursive: true, force: true })
  }
}

await main()
